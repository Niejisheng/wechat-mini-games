const assert = require('assert')
const sudoku = require('../src/games/sudoku/logic')

const state = sudoku.gameFromPuzzle()
let game = sudoku.reducer(state, { type: 'filter', digit: 4 })
assert.strictEqual(game.filter, 4)
game = sudoku.reducer(game, { type: 'select', index: 2 })
assert.strictEqual(game.filter, 4)
const beforeNotes = game.notes[2]
game = sudoku.reducer(game, { type: 'note', digit: 4 })
assert.strictEqual(game.filter, 4)
assert.strictEqual(game.notes[2], beforeNotes)
assert.ok(game.exclusions[2] & (1 << 4))
game = sudoku.reducer(game, { type: 'input', digit: 4 })
assert.strictEqual(game.values[2], 4)
assert.strictEqual(game.notes[2], 0)
assert.strictEqual(game.exclusions[2], 0)
assert.ok(game.history.length > 0)
game = sudoku.reducer(game, { type: 'undo' })
assert.strictEqual(game.values[2], 0)
assert.strictEqual(game.filter, 4)
assert.strictEqual(sudoku.conflicts(game.values).size, 0)

let notesGame = sudoku.reducer(sudoku.gameFromPuzzle(), { type: 'select', index: 2 })
notesGame = sudoku.reducer(notesGame, { type: 'note', digit: 4 })
assert.ok(notesGame.notes[2] & (1 << 4))
assert.strictEqual(notesGame.exclusions[2] & (1 << 4), 0)
assert.ok(sudoku.availableCandidates(notesGame.values, 2, notesGame.exclusions) & (1 << 4))
notesGame = sudoku.reducer(notesGame, { type: 'note', digit: 4 })
assert.strictEqual(notesGame.notes[2] & (1 << 4), 0)
assert.ok(notesGame.exclusions[2] & (1 << 4))
assert.strictEqual(sudoku.availableCandidates(notesGame.values, 2, notesGame.exclusions) & (1 << 4), 0)

console.log('sudoku logic tests passed')
